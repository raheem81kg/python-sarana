def generate(ast):
    """
    Generate Python code from a Sarana AST.
    
    Args:
        ast: Program node (root of AST)
        
    Returns:
        str: Generated Python source code
        
    Example:
        >>> from lexer import tokenize
        >>> from parser import parse
        >>> from codegen import generate
        >>> 
        >>> code = 'bloom x = 5; echo x;'
        >>> tokens = tokenize(code)
        >>> ast = parse(tokens)
        >>> python_code = generate(ast)
        >>> print(python_code)
        # Generated Python code from Sarana
        # This file was automatically generated by the Sarana compiler
        
        x = 5
        print(x)
    """
    generator = CodeGenerator()
    return generator.generate(ast)


def generate_to_file(ast, output_path):
    """
    Generate Python code and write it to a file.
    
    Args:
        ast: Program node (root of AST)
        output_path: Path to output .py file
        
    Returns:
        str: Generated Python source code (also written to file)
        
    Example:
        >>> from codegen import generate_to_file
        >>> generate_to_file(ast, 'output/generated.py')
    """
    python_code = generate(ast)
    
    with open(output_path, 'w') as f:
        f.write(python_code)
    
    return python_code
